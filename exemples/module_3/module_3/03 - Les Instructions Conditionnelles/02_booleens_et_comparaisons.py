"""
Exemple 2 — Booléens et comparaisons

Une comparaison produit une valeur booléenne :
True ou False.
"""

age = 18

print("age > 18  :", age > 18)
print("age >= 18 :", age >= 18)
print("age == 18 :", age == 18)
print("age != 18 :", age != 18)
print("age < 18  :", age < 18)

# = affecte une valeur
x = 10

# == compare deux valeurs
print("x vaut-il 10 ?", x == 10)
