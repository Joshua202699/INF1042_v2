"""
Exemple 2 — Paramètres et arguments

Paramètre : nom utilisé dans la définition de la fonction.
Argument  : valeur réelle donnée lorsque la fonction est appelée.
"""

def saluer(nom):  # 'nom' est un paramètre
    print("Bonjour", nom, "!")


saluer("Alex")     # "Alex" est un argument
saluer("Sofia")    # "Sofia" est un autre argument
