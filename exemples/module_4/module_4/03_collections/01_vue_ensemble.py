"""Vue d'ensemble des quatre collections principales de Python."""

# LISTE : ordonnée, mutable, doublons permis.
ma_liste = [10, 20, 20]

# TUPLE : ordonné, immuable, doublons permis.
mon_tuple = (10, 20, 20)

# SET (ensemble) : valeurs uniques; ne pas se fier à l'ordre d'affichage.
mon_set = {10, 20, 20}

# DICTIONNAIRE : paires clé-valeur.
mon_dict = {"a": 10, "b": 20}

print("Liste :", ma_liste)
print("Tuple :", mon_tuple)
print("Set :", mon_set)
print("Dictionnaire :", mon_dict)
